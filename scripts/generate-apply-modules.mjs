/**
 * Generate supabase/apply-modules.sql by EXTRACTING sections 7 (`raw`) and 8
 * (`time`) from schema.sql.
 *
 * Extracted, never hand-copied. A hand-maintained duplicate of 400 lines of DDL
 * is a second source of truth that drifts silently, and the drift only shows up
 * as a production bug. Running this regenerates the file; check-apply-modules
 * asserts it is in step.
 */
import { readFileSync, writeFileSync } from "node:fs";

const schema = readFileSync("supabase/schema.sql", "utf8");
const nl = schema.includes("\r\n") ? "\r\n" : "\n";

// Section headers in schema.sql look like:
//   -- 7. raw -- the vendor landing zone
const startMarker = schema.search(/^-- 7\. raw/m);
if (startMarker === -1) {
  console.error("could not find section 7 (raw) in schema.sql");
  process.exit(1);
}

// Back up to the banner comment line that opens the section.
const beforeStart = schema.lastIndexOf("-- ---", startMarker);
const body = schema.slice(beforeStart);

const header = `-- ---------------------------------------------------------------------------
-- Bring the \`raw\` and \`time\` module schemas up on an EXISTING database.
-- ---------------------------------------------------------------------------
-- GENERATED by scripts/generate-apply-modules.mjs from supabase/schema.sql.
-- Do not edit by hand: edit schema.sql and regenerate. A hand-maintained copy of
-- this much DDL is a second source of truth, and its drift surfaces only as a
-- production bug.
--
-- Why a separate file at all: schema.sql is not end-to-end idempotent. Section 1
-- creates the legacy netflix_users/files policies with no \`if not exists\` guard,
-- so re-running the whole file against a live database dies at the first policy
-- with 42710 "policy already exists" -- long before it reaches the module
-- sections. Sections 7 and 8 below ARE guarded and safe to re-run.
--
-- ---------------------------------------------------------------------------
-- STEP 1 of 2  Run this file in the Supabase SQL Editor.
--
-- STEP 2 of 2  Dashboard -> Project Settings -> API -> "Exposed schemas".
--              Set it to:   public, graphql_public, raw, time
--
--              This one cannot be done from SQL. PostgREST only serves schemas
--              in that list; until \`time\` appears there every query answers
--              406 PGRST106 "Invalid schema", the query layer turns that into an
--              empty result by design, and /time shows "No time-tracking record
--              linked to your account" to every user while looking healthy.
--
-- Verify both:  npm run check:live-ready
-- Background:   docs/architecture/MODULE-GO-LIVE.md
-- ---------------------------------------------------------------------------

`;

const out = header + body.trimEnd() + nl;
writeFileSync("supabase/apply-modules.sql", out);

const lines = out.split(/\r?\n/).length;
const tables = (out.match(/create table if not exists/g) || []).length;
const policies = (out.match(/^[ \t]*create policy/gim) || []).length;
console.log(`wrote supabase/apply-modules.sql: ${lines} lines, ${tables} tables, ${policies} policies`);
